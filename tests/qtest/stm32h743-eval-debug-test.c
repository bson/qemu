/*
 * Debug register addresses (ARMv7-M architectural, part of the NVIC's
 * own MMIO region).
 */
#define DHCSR 0xE000EDF0
#define DCRDR 0xE000EDF8
#define DEMCR 0xE000EDFC
#define DFSR  0xE000ED30

#define DEMCR_MON_EN   (1u << 16)

#define DHCSR_C_DEBUGEN (1u << 0)
#define DHCSR_S_REGRDY  (1u << 16)
#define DHCSR_DBGKEY    (0xa05fu << 16)

/* FPB (hw/misc/armv7m_fpb.c) */
#define FP_CTRL  0xE0002000
#define FP_COMP0 0xE0002008

#define FP_CTRL_ENABLE (1u << 0)
#define FP_CTRL_KEY    (1u << 1)

/* DWT (hw/misc/armv7m_dwt.c) */
#define DWT_CTRL      0xE0001000
#define DWT_COMP0     0xE0001020
#define DWT_MASK0     0xE0001024
#define DWT_FUNCTION0 0xE0001028

#define RAM_BASE 0x20000000

